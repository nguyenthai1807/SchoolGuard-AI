"""Package the reviewed browser-only Free analyzer for Firebase Spark Hosting.

Only static runtime files and three Free COCO person models are copied. No
private media, credentials, payOS code, or server endpoints are published.
"""

from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "hosting" / "firebase-spark" / "app"
CLIENT = ROOT / "browser-client"
DIST = ROOT / "tools" / "browser-runtime" / "node_modules" / "onnxruntime-web" / "dist"
CLIENT_FILES = ("browser.js", "browser.css", "detection.mjs", "inference-worker.js", "effort.mjs")
VENDOR_FILES = ("ort.wasm.min.mjs", "ort-wasm-simd-threaded.mjs", "ort-wasm-simd-threaded.wasm")
FREE_MODELS = ("yolov8n", "yolov9t", "yolov10n")
SHELL_FILES = ("style.css", "lh25.css", "lh25-green.css", "brand-lh25-original.jpg")


def build() -> None:
    models = [ROOT / "models" / f"{name}.onnx" for name in FREE_MODELS]
    required = ([CLIENT / name for name in CLIENT_FILES]
                + [DIST / name for name in VENDOR_FILES] + models
                + [ROOT / "schoolguard" / "static" / name for name in SHELL_FILES])
    missing = [path for path in required if not path.is_file()]
    if missing:
        raise RuntimeError("Missing Free browser prerequisites: " + ", ".join(path.name for path in missing))
    (TARGET / "vendor").mkdir(parents=True, exist_ok=True)
    (TARGET / "models").mkdir(parents=True, exist_ok=True)
    (TARGET / "static").mkdir(parents=True, exist_ok=True)
    # Generated by the previous Free build; no longer referenced by the UI.
    legacy_model = TARGET / "models" / "person.onnx"
    if legacy_model.is_file():
        legacy_model.unlink()
    for name in CLIENT_FILES:
        shutil.copyfile(CLIENT / name, TARGET / name)
    for name in VENDOR_FILES:
        shutil.copyfile(DIST / name, TARGET / "vendor" / name)
    for name, model in zip(FREE_MODELS, models):
        shutil.copyfile(model, TARGET / "models" / f"{name}.onnx")
    for name in SHELL_FILES:
        shutil.copyfile(ROOT / "schoolguard" / "static" / name, TARGET / "static" / name)
    print("Firebase Free browser runtime and LH25 shell packaged: YOLO8n/9t/10n, no backend or payment code.")


if __name__ == "__main__":
    build()
